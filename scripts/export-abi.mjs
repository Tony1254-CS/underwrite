#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const contracts = ['UnderwriteVault', 'MockUSDC'];
const outDir = path.join(rootDir, 'contracts', 'out');
const targetAbiDir = path.join(rootDir, 'engine', 'src', 'chain', 'abi');

if (!fs.existsSync(targetAbiDir)) {
  fs.mkdirSync(targetAbiDir, { recursive: true });
}

for (const name of contracts) {
  const artifactPath = path.join(outDir, `${name}.sol`, `${name}.json`);
  if (!fs.existsSync(artifactPath)) {
    console.error(`Error: Artifact not found at ${artifactPath}. Run forge build first.`);
    process.exit(1);
  }

  const raw = fs.readFileSync(artifactPath, 'utf8');
  const parsed = JSON.parse(raw);
  const abi = parsed.abi;

  if (!abi) {
    console.error(`Error: No abi field found in ${artifactPath}`);
    process.exit(1);
  }

  const jsonOutPath = path.join(targetAbiDir, `${name}.json`);
  fs.writeFileSync(jsonOutPath, JSON.stringify(abi, null, 2) + '\n', 'utf8');
  console.log(`Exported JSON ABI to ${jsonOutPath}`);

  const tsOutPath = path.join(targetAbiDir, `${name}.ts`);
  const tsContent = `// Auto-generated by scripts/export-abi.mjs - DO NOT EDIT MANUALLY\nexport const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
  fs.writeFileSync(tsOutPath, tsContent, 'utf8');
  console.log(`Exported TypeScript ABI to ${tsOutPath}`);
}

console.log('ABI export complete.');
